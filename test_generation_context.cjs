const assert = require('node:assert/strict');
require('./generation_context.js');
const info = globalThis.generationInfo;
const reference = {name:'左侧参考声音'};
const designed = info({engine:'qwen',mode:'design',reference,instruction:'温暖女声',voice_design_template:'温暖女旁白'});
assert.match(designed.model,/VoiceDesign/);
assert.equal(designed.usesReference,false);
assert.equal(designed.voice,'温暖女旁白');
assert.equal(designed.description,'温暖女声');
const cloned = info({engine:'qwen',mode:'clone',reference,voice_design_template:'旧模板'});
assert.match(cloned.model,/Base/);
assert.equal(cloned.usesReference,true);
assert.equal(cloned.voice,reference.name);
const preset = info({engine:'qwen',mode:'custom',speaker:'Vivian',reference},[{id:'Vivian',name:'明亮年轻女声'}]);
assert.match(preset.model,/CustomVoice/);
assert.equal(preset.voice,'明亮年轻女声');
assert.equal(preset.usesReference,false);
assert.equal(info({engine:'qwen',mode:'design',reference}).voice,'自定义音色描述');
assert.equal(info({engine:'index',reference,mode:'design'}).usesReference,true);
assert.equal(info({engine:'spark',mode:'design',reference,gender:'male',spark_seed:123}).voice,'男声 · 候选 123');
assert.equal(info({engine:'spark',mode:'clone',reference}).voice,reference.name);
console.log('生成配置检查通过：Qwen 三种模式、参考声音生效范围、Spark 候选、旧记录。');
